from __future__ import annotations

from typing import Any


def cadquery_code(spec: dict[str, Any]) -> str:
    equipment = spec["equipment"]
    params = spec["parameters"]
    header = [
        "# Candidate CAD generated from Tri-MRO photo observation.",
        "# Review required: this is not a measurement-grade or manufacturing model.",
        "import cadquery as cq",
        "",
    ]
    if equipment == "bearing":
        return "\n".join(
            header
            + [
                f"outer_diameter = {params['outer_diameter']}",
                f"inner_diameter = {params['inner_diameter']}",
                f"width = {params['width']}",
                "outer_ring = cq.Workplane('XY').circle(outer_diameter / 2).circle(inner_diameter / 2).extrude(width)",
                "rolling_path = cq.Workplane('XY').circle((outer_diameter + inner_diameter) / 4).extrude(width * 0.12)",
                "result = outer_ring.union(rolling_path)",
                "show_object(result)",
            ]
        )
    if equipment == "pump":
        return "\n".join(
            header
            + [
                f"body_length = {params['body_length']}",
                f"body_height = {params['body_height']}",
                f"port_diameter = {params['port_diameter']}",
                "shaft_diameter = 18",
                "casing = cq.Workplane('YZ').circle(body_height * 0.46).extrude(58).translate((-29, 0, 0))",
                "front_cover = cq.Workplane('YZ').circle(body_height * 0.34).extrude(12).translate((-47, 0, 0))",
                "inlet = cq.Workplane('YZ').circle(port_diameter / 2).extrude(92).translate((-132, 0, 0))",
                "inlet_flange = cq.Workplane('YZ').circle(port_diameter * 0.66).extrude(12).translate((-138, 0, 0))",
                "outlet = cq.Workplane('XY').circle(port_diameter * 0.41).extrude(82).translate((0, 0, body_height * 0.31))",
                "outlet_flange = cq.Workplane('XY').circle(port_diameter * 0.55).extrude(12).translate((0, 0, body_height * 0.31 + 76))",
                "seal_zone = cq.Workplane('YZ').circle(27).circle(11).extrude(24).translate((44, 0, 0))",
                "shaft = cq.Workplane('YZ').circle(shaft_diameter / 2).extrude(138).translate((68, 0, 0))",
                "base = cq.Workplane('XY').box(126, 86, 12).translate((12, 0, -body_height * 0.56))",
                "foot_a = cq.Workplane('XY').box(32, 22, 18).translate((-36, -32, -body_height * 0.42))",
                "foot_b = cq.Workplane('XY').box(32, 22, 18).translate((60, 32, -body_height * 0.42))",
                "result = casing.union(front_cover).union(inlet).union(inlet_flange).union(outlet).union(outlet_flange).union(seal_zone).union(shaft).union(base).union(foot_a).union(foot_b)",
                "show_object(result)",
            ]
        )
    if equipment == "motor":
        return "\n".join(
            header
            + [
                f"body_length = {params['body_length']}",
                f"body_diameter = {params['body_diameter']}",
                f"shaft_diameter = {params['shaft_diameter']}",
                "body = cq.Workplane('YZ').circle(body_diameter / 2).extrude(body_length)",
                "shaft = cq.Workplane('YZ').circle(shaft_diameter / 2).extrude(body_length * 1.25)",
                "terminal = cq.Workplane('XY').box(42, 32, 28).translate((body_length * 0.15, 0, body_diameter / 2 + 14))",
                "result = body.union(shaft).union(terminal)",
                "show_object(result)",
            ]
        )
    return "\n".join(
        header
        + [
            f"block_width = {params.get('block_width', 120)}",
            f"block_height = {params.get('block_height', 130)}",
            "block = cq.Workplane('XY').box(block_width, 70, block_height).edges('|Z').fillet(4)",
            "spark_plug = cq.Workplane('XY').circle(7).extrude(36).translate((0, 0, block_height / 2))",
            "result = block.union(spark_plug)",
            "show_object(result)",
        ]
    )


def openscad_code(spec: dict[str, Any]) -> str:
    equipment = spec["equipment"]
    p = spec["parameters"]
    header = "// Candidate CAD generated by Tri-MRO. Human review required.\n$fn = 72;\n"
    if equipment == "bearing":
        return (
            header
            + f"difference() {{ cylinder(h={p['width']}, d={p['outer_diameter']}); cylinder(h={p['width'] + 1}, d={p['inner_diameter']}); }}\n"
            + f"for (i=[0:{p['ball_count'] - 1}]) rotate([0,0,i*360/{p['ball_count']}]) translate([{(p['outer_diameter'] + p['inner_diameter']) / 4},0,{p['width']/2}]) sphere(d=6);\n"
        )
    if equipment == "pump":
        return (
            header
            + f"translate([-29,0,0]) rotate([0,90,0]) cylinder(h=58, d={p['body_height'] * 0.92}, center=true);\n"
            + f"translate([-47,0,0]) rotate([0,90,0]) cylinder(h=12, d={p['body_height'] * 0.68}, center=true);\n"
            + f"translate([-132,0,0]) rotate([0,90,0]) cylinder(h=92, d={p['port_diameter']}, center=true);\n"
            + f"translate([-138,0,0]) rotate([0,90,0]) cylinder(h=12, d={p['port_diameter'] * 1.32}, center=true);\n"
            + f"translate([0,0,{p['body_height'] * 0.31}]) cylinder(h=82, d={p['port_diameter'] * 0.82}, center=false);\n"
            + f"translate([0,0,{p['body_height'] * 0.31 + 76}]) cylinder(h=12, d={p['port_diameter'] * 1.10}, center=false);\n"
            + "color(\"orange\") translate([44,0,0]) rotate([0,90,0]) difference() { cylinder(h=24, d=54, center=true); cylinder(h=26, d=22, center=true); }\n"
            + "translate([68,0,0]) rotate([0,90,0]) cylinder(h=138, d=18, center=true);\n"
            + f"translate([12,0,{-p['body_height'] * 0.56}]) cube([126,86,12], center=true);\n"
            + f"translate([-36,-32,{-p['body_height'] * 0.42}]) cube([32,22,18], center=true);\n"
            + f"translate([60,32,{-p['body_height'] * 0.42}]) cube([32,22,18], center=true);\n"
        )
    if equipment == "motor":
        return (
            header
            + f"rotate([0,90,0]) cylinder(h={p['body_length']}, d={p['body_diameter']}, center=true);\n"
            + f"rotate([0,90,0]) cylinder(h={p['body_length'] * 1.25}, d={p['shaft_diameter']}, center=true);\n"
            + "translate([0,0,60]) cube([48,34,28], center=true);\n"
        )
    return (
        header
        + f"cube([{p.get('block_width', 120)},70,{p.get('block_height', 130)}], center=true);\n"
        + f"translate([0,0,{p.get('block_height', 130)/2}]) cylinder(h=36, d={p.get('spark_plug_diameter', 14)}, center=false);\n"
    )
