-- A1 maintenance assistant public-demo persistence schema.
-- Run this in the Supabase SQL editor before enabling SUPABASE_ENABLED=true.

create table if not exists public.a1_maintenance_cases (
  id bigint generated by default as identity primary key,
  local_id bigint unique not null,
  title text not null,
  equipment text not null,
  model text default '',
  symptoms text not null,
  fault_type text not null,
  cause text not null,
  actions text not null,
  parts text default '',
  risk_level text default 'medium',
  status text not null default 'pending',
  created_at timestamptz not null,
  review_status text default 'unreviewed',
  reviewer text default '',
  review_notes text default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.a1_feedback (
  id bigint generated by default as identity primary key,
  local_id bigint unique not null,
  question text not null,
  original_answer text not null,
  corrected_answer text not null,
  notes text default '',
  created_at timestamptz not null,
  updated_at timestamptz not null default now()
);

alter table public.a1_maintenance_cases enable row level security;
alter table public.a1_feedback enable row level security;

